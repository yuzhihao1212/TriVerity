"""Precedent knowledge base: past rulings and the retrieval over them.

Each precedent records a past dispute's key facts as numbers ("features"), a short
summary, the decision and who made it (the policy rules, or a human reviewer). The
seed set in ``data/precedents/precedents.json`` is synthetic, generated by
``scripts/build_precedents.py``. Reviewer decisions sent to the feedback endpoint are
added in memory (the learning feedback loop); a production system would store them.

Retrieval is deterministic: similar cases are found by distance between their
features, scaled so that one unit is a meaningful difference (10 percentage points of
detour, 50 m from pickup, 2 min of waiting). Nothing here calls an LLM.
"""

from __future__ import annotations

import json
import threading
from functools import cache
from math import sqrt

from pydantic import BaseModel, Field

from app.core import limits
from app.models.dispute import DisputeType
from app.models.resolution import Decision, PrecedentMatch
from app.services.evidence import CaseFacts
from app.services.policy_service import DATA_ROOT

PRECEDENTS_PATH = DATA_ROOT / "precedents" / "precedents.json"

# One unit of distance per feature. Booleans count 1 when they differ.
_SCALES = {"distance_excess": 0.1, "duration_excess": 0.1, "pickup_distance_m": 50.0, "wait_min": 2.0}
_MISSING_PENALTY = 1.0   # a feature unknown on either side counts as a full unit apart


class Precedent(BaseModel):
    id: str
    dispute_type: DisputeType
    features: dict[str, float | bool | None]
    summary: str
    decision: Decision
    policy_refs: list[str] = Field(default_factory=list)
    decided_by: str = "policy"
    note: str = ""
    # Public demo: the judge access-code ID whose sandbox this decision belongs to. None:
    # shared (the seed set, and every decision outside the public demo).
    owner: str | None = None


def case_features(dispute_type: str, facts: CaseFacts) -> dict[str, float | bool | None]:
    """The facts the rules turn on, for one dispute type."""
    if dispute_type == "route_deviation":
        return {"distance_excess": facts.distance_excess_ratio, "duration_excess": facts.duration_excess_ratio}
    return {
        "pickup_distance_m": facts.driver_distance_from_pickup_m,
        "wait_min": facts.driver_wait_min,
        "contact": facts.driver_contact_attempted,
    }


def summarise(dispute_type: str, features: dict) -> str:
    """A neutral one-line description of a case, built only from its features."""
    def pct(value: float | None, what: str) -> str:
        if value is None:
            return f"{what} unknown"
        return f"{abs(value):.0%} {'longer' if value >= 0 else 'shorter'}" if what == "route" else \
            f"{abs(value):.0%} {'slower' if value >= 0 else 'faster'}"
    if dispute_type == "route_deviation":
        return f"Route {pct(features.get('distance_excess'), 'route')} than expected, trip " \
               f"{pct(features.get('duration_excess'), 'trip')} than expected"
    distance, wait = features.get("pickup_distance_m"), features.get("wait_min")
    parts = [f"driver stopped {distance:.0f} m from pickup" if distance is not None else "arrival location unknown",
             f"waited {wait:g} min" if wait is not None else "wait unknown",
             "contacted the rider" if features.get("contact") else "no contact attempt"]
    return "No-show: " + ", ".join(parts)


def similarity(a: dict, b: dict) -> float:
    """1.0 for identical features, falling towards 0 as they differ."""
    distance_sq = 0.0
    for key in a.keys() | b.keys():
        x, y = a.get(key), b.get(key)
        if x is None or y is None:
            distance_sq += _MISSING_PENALTY ** 2
        elif isinstance(x, bool) or isinstance(y, bool):
            distance_sq += 0.0 if bool(x) == bool(y) else 1.0
        else:
            distance_sq += ((float(x) - float(y)) / _SCALES.get(key, 1.0)) ** 2
    return 1.0 / (1.0 + sqrt(distance_sq))


@cache
def _seed() -> tuple[Precedent, ...]:
    data = json.loads(PRECEDENTS_PATH.read_text())
    return tuple(Precedent(**item) for item in data["precedents"])


_feedback: list[Precedent] = []
_feedback_lock = threading.Lock()


def all_precedents(owner: str | None = None) -> list[Precedent]:
    """The shared precedents, plus ``owner``'s own sandbox (public demo) when given."""
    with _feedback_lock:
        return [*_seed(), *(p for p in _feedback if p.owner is None or p.owner == owner)]


def retrieve(dispute_type: str, facts: CaseFacts, k: int = limits.PRECEDENT_TOP_K,
             owner: str | None = None) -> list[PrecedentMatch]:
    """The ``k`` most similar past rulings of the same dispute type, as ``owner`` sees them."""
    query = case_features(dispute_type, facts)
    scored = [(similarity(query, p.features), p) for p in all_precedents(owner) if p.dispute_type == dispute_type]
    scored = [(s, p) for s, p in scored if s >= limits.PRECEDENT_SHOW_MIN_SIMILARITY]
    # Most similar first; a reviewer's decision before the rules' on a tie; then by ID for stable output.
    scored.sort(key=lambda sp: (-round(sp[0], 3), sp[1].decided_by != "human_review", sp[1].id))
    return [
        PrecedentMatch(id=p.id, similarity=round(s, 3), decision=p.decision, policy_refs=p.policy_refs,
                       decided_by="human_review" if p.decided_by == "human_review" else "policy",
                       summary=p.summary, note=p.note)
        for s, p in scored[:k]
    ]


class FeedbackFull(Exception):
    """The in-memory feedback store is full."""


def add_feedback(dispute_type: str, facts: CaseFacts, decision: Decision, note: str,
                 owner: str | None = None) -> Precedent:
    """Record a human reviewer's decision as a new precedent (the learning feedback loop).

    With ``owner`` (public demo) it joins only that judge's sandbox, capped per judge.
    """
    with _feedback_lock:
        if len(_feedback) >= limits.PRECEDENT_MAX_FEEDBACK:
            raise FeedbackFull
        if owner is not None and sum(p.owner == owner for p in _feedback) >= limits.SANDBOX_MAX_PER_CODE:
            raise FeedbackFull
        features = case_features(dispute_type, facts)
        precedent = Precedent(
            id=f"R-{len(_feedback) + 1:03d}",
            dispute_type=dispute_type,
            features=features,
            summary=summarise(dispute_type, features),
            decision=decision,
            decided_by="human_review",
            note=note,
            owner=owner,
        )
        _feedback.append(precedent)
        return precedent


def clear_feedback() -> None:
    """Forget every reviewer decision (tests, and a demo reset)."""
    with _feedback_lock:
        _feedback.clear()
