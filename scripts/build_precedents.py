"""Build the synthetic precedent knowledge base: data/precedents/precedents.json.

Past rulings for a grid of route-deviation and no-show cases, each decided by the
current policy rules (decided_by "policy"), plus a few synthetic human-reviewer
decisions (decided_by "human_review") that went against the rules for a stated
reason. The reviewer clusters sit away from every sample dispute, so the samples'
rulings don't change; they exist to demonstrate rule PREC-1. No LLM is called.

Usage (from the repo root, with the backend venv active):
    python scripts/build_precedents.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.agents.judge_agent import base_ruling  # noqa: E402
from app.models.dispute import DisputeCase  # noqa: E402
from app.services.evidence import CaseFacts  # noqa: E402
from app.services.precedents import PRECEDENTS_PATH, summarise  # noqa: E402

ROUTE_EXCESS = [0.05, 0.1, 0.15, 0.18, 0.22, 0.3, 0.35, 0.4, 0.45, 0.5, 0.6]
ROUTE_DURATION = [-0.2, -0.1, 0.05, 0.1, 0.3, 0.45, 0.6]
NO_SHOW_DISTANCE_M = [10, 30, 60, 90, 130, 250, 350, 450]
NO_SHOW_WAIT_MIN = [2, 4, 6, 8, 10]

# Synthetic reviewer decisions that overruled the rules, with the reason a reviewer gave.
REVIEWER_CLUSTERS = [
    ("route_deviation", [(0.25, 0.08), (0.27, 0.10), (0.26, 0.06)], "no_action",
     "Reviewer: the usual road was closed; the detour was the shortest open route."),
    ("no_show_charge", [(160, 7, True), (170, 8, True)], "no_action",
     "Reviewer: the pickup pin was inside a mall; the driver waited at the nearest legal stop."),
]


def _rule_ids(refs: list[str]) -> list[str]:
    return [ref.split(":", 1)[0] for ref in refs]


def _decide(dispute_type: str, facts: CaseFacts) -> tuple[str, list[str]]:
    case = DisputeCase(dispute_id="P-GEN", type=dispute_type, rider_claim="Synthetic precedent.",
                       fare={"cancellation_fee": 5.0} if dispute_type == "no_show_charge" else {})
    ruling = base_ruling(case, facts)
    return ruling.decision, _rule_ids(ruling.policy_refs)


def _route_facts(excess: float, duration: float) -> CaseFacts:
    return CaseFacts(dispute_type="route_deviation", distance_excess_ratio=excess,
                     duration_excess_ratio=duration, fare_difference=round(15 * excess * 0.8, 2))


def _no_show_facts(distance: float, wait: float, contact: bool) -> CaseFacts:
    return CaseFacts(dispute_type="no_show_charge", driver_distance_from_pickup_m=distance,
                     driver_wait_min=wait, driver_contact_attempted=contact)


def build() -> list[dict]:
    from app.services.precedents import case_features
    cases = [("route_deviation", _route_facts(e, d)) for e in ROUTE_EXCESS for d in ROUTE_DURATION]
    cases += [("no_show_charge", _no_show_facts(m, w, c))
              for m in NO_SHOW_DISTANCE_M for w in NO_SHOW_WAIT_MIN for c in (True, False)]
    items = []
    for dispute_type, facts in cases:
        decision, refs = _decide(dispute_type, facts)
        features = case_features(dispute_type, facts)
        items.append({"dispute_type": dispute_type, "features": features,
                      "summary": summarise(dispute_type, features), "decision": decision,
                      "policy_refs": refs, "decided_by": "policy", "note": ""})
    for dispute_type, points, decision, note in REVIEWER_CLUSTERS:
        for point in points:
            facts = _route_facts(*point) if dispute_type == "route_deviation" else _no_show_facts(*point)
            features = case_features(dispute_type, facts)
            items.append({"dispute_type": dispute_type, "features": features,
                          "summary": summarise(dispute_type, features), "decision": decision,
                          "policy_refs": [], "decided_by": "human_review", "note": note})
    return [{"id": f"P-{i:03d}", **item} for i, item in enumerate(items, start=1)]


def main() -> None:
    precedents = build()
    PRECEDENTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    PRECEDENTS_PATH.write_text(json.dumps({
        "_note": "Synthetic precedent knowledge base generated by scripts/build_precedents.py. "
                 "decided_by 'policy': the current policy rules' decision, accepted. "
                 "decided_by 'human_review': a synthetic reviewer decision that overruled the rules.",
        "precedents": precedents,
    }, indent=1) + "\n")
    print(f"Wrote {len(precedents)} precedents to {PRECEDENTS_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
